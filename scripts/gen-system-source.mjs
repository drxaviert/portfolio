// Extracts the engine's source tokens from the shipped CSS.
//
// The CSS is the source of truth. This script parses the real text (never a
// hand-mirrored table) into `src/lib/system/source.generated.ts`, and the
// parity test re-parses the same text through an independent oracle.
// Run with `pnpm gen:system`.

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const GLOBALS_PATH = path.resolve(process.cwd(), "src/app/globals.css");
const ENTRANCE_PATH = path.resolve(
  process.cwd(),
  "src/components/home/home-entrance.css",
);
const OUTPUT_PATH = path.resolve(
  process.cwd(),
  "src/lib/system/source.generated.ts",
);

const PHASES = ["dawn", "day", "dusk", "night"];

function stripComments(css) {
  return css.replace(/\/\*[\s\S]*?\*\//g, "");
}

function declarations(body) {
  const result = {};

  for (const match of body.matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)) {
    result[match[1]] = match[2].trim().replace(/\s+/g, " ");
  }

  return result;
}

function blocks(css) {
  const result = [];

  for (const match of stripComments(css).matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
    result.push({
      selectors: match[1].split(",").map((selector) => selector.trim()),
      body: match[2],
    });
  }

  return result;
}

function pickPrefix(source, prefix) {
  return Object.fromEntries(
    Object.entries(source).filter(([name]) => name.startsWith(prefix)),
  );
}

const phaseSelector = /^\[data-phase="(dawn|day|dusk|night)"\]$/;

export function extract() {
  const root = {};
  const roles = { dawn: {}, day: {}, dusk: {}, night: {} };
  const theme = {};

  for (const block of blocks(readFileSync(GLOBALS_PATH, "utf8"))) {
    const values = declarations(block.body);

    for (const selector of block.selectors) {
      if (selector === ":root") Object.assign(root, values);

      const phase = selector.match(phaseSelector)?.[1];

      if (phase) Object.assign(roles[phase], values);

      if (selector.startsWith("@theme")) Object.assign(theme, values);
    }
  }

  const durations = pickPrefix(root, "--duration-");

  for (const block of blocks(readFileSync(ENTRANCE_PATH, "utf8"))) {
    const isEntranceScope =
      block.selectors.includes(".entrance-scope") ||
      block.selectors.includes('[data-entrance="soft"]');

    if (!isEntranceScope) continue;

    for (const [name, value] of Object.entries(declarations(block.body))) {
      if (
        /^-?\d*\.?\d+m?s$/.test(value) ||
        /^var\(--duration-[\w-]+\)$/.test(value)
      ) {
        durations[name] = value;
      }
    }
  }

  return {
    PALETTE: pickPrefix(root, "--palette-"),
    ROLES: Object.fromEntries(
      PHASES.map((phase) => [phase, roles[phase]]),
    ),
    RADII: pickPrefix(theme, "--radius-"),
    DURATIONS: durations,
    EASES: pickPrefix(root, "--ease-"),
  };
}

function render() {
  const { PALETTE, ROLES, RADII, DURATIONS, EASES } = extract();

  return `// generated by pnpm gen:system, do not edit

import type { Phase } from "@/lib/theme";

export type { Phase };

export const PALETTE: Record<string, string> = ${JSON.stringify(PALETTE, null, 2)};

export const ROLES: Record<Phase, Record<string, string>> = ${JSON.stringify(ROLES, null, 2)};

export const RADII: Record<string, string> = ${JSON.stringify(RADII, null, 2)};

export const DURATIONS: Record<string, string> = ${JSON.stringify(DURATIONS, null, 2)};

export const EASES: Record<string, string> = ${JSON.stringify(EASES, null, 2)};
`;
}

const isDirectRun =
  process.argv[1] !== undefined &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (isDirectRun) {
  writeFileSync(OUTPUT_PATH, render());
  process.stdout.write(`wrote ${OUTPUT_PATH}\n`);
}
